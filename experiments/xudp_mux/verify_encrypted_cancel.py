"""Strict supplemental verifier; import alongside xudp_mux/verify_evidence.py.

No fixture generated by this module is runtime evidence. Scope is encrypted
library callers, explicitly not actual ConnectionManager/official-device.
"""
import json
from pathlib import Path

CIPHERS = {
    'TestMuxEncryptedCancelAES': 'aes-128-gcm',
    'TestMuxEncryptedCancelChaCha': 'chacha20-poly1305',
}
LEAVES = (
    'PartialAuthenticatedLength', 'PartialCiphertextPayload', 'QueuedCancel',
    'CompletionBeforeClose', 'ParentTransportError',
)
PREFIX = 'XUDP_ENCRYPTED_CANCEL '


def need(condition, message):
    if not condition:
        raise ValueError(message)


def verify_encrypted_cancel(path):
    rows = [json.loads(line) for line in Path(path).read_text().splitlines() if line.strip()]
    need(rows and all(isinstance(row, dict) for row in rows), 'Empty/invalid encrypted cancellation evidence')
    need(all(row.get('Package') == 'github.com/sagernet/sing-vmess' for row in rows), 'Wrong Go evidence package')
    expected = set(CIPHERS) | {top + '/' + leaf for top in CIPHERS for leaf in LEAVES}
    terminal = {}
    events = {name: [] for name in expected if '/' in name}
    pending_output = {}
    for row in rows:
        if row.get('Action') in ('pass', 'skip', 'fail') and row.get('Test'):
            name = row['Test']
            need(name not in terminal, 'Duplicate cancellation test terminal: ' + name)
            terminal[name] = row['Action']
        output = row.get('Output', '')
        if output:
            need(row.get('Action') == 'output', 'Event is not test output')
            source = (row['Package'], row.get('Test'))
            pending_output[source] = pending_output.get(source, '') + output
            while '\n' in pending_output[source]:
                line, pending_output[source] = pending_output[source].split('\n', 1)
                if PREFIX not in line:
                    continue
                data = json.loads(line.split(PREFIX, 1)[1])
                name = data.get('case')
                need(name in events and source[1] == name, 'Event has wrong leaf/source')
                events[name].append(data)
    need(not any(pending_output.values()), 'Unterminated split evidence output')
    need(set(terminal) == expected, 'Missing/unexpected encrypted cancellation top-level or leaf test')
    need(all(value == 'pass' for value in terminal.values()), 'Failed/skipped encrypted cancellation test')
    package_terminals = [row['Action'] for row in rows if row.get('Action') in ('pass', 'skip', 'fail') and 'Test' not in row]
    need(package_terminals == ['pass'], 'Encrypted cancellation package did not uniquely pass')
    for name, event_list in events.items():
        top, leaf = name.split('/')
        common = ['cipher_continuity', 'warmup_complete', 'wire_blocked']
        if leaf == 'ParentTransportError':
            order = common + ['parent_error_snapshot', 'parent_close', 'parent_joined']
        else:
            middle = (['restore_reads', 'completion_before_close'] if leaf == 'CompletionBeforeClose'
                      else ['cancel_snapshot', 'restore_reads'])
            order = common + middle + ['cipher_continuity', 'siblings_recovered', 'cipher_continuity', 'fresh_session_recovered', 'cipher_continuity',
                                       'drained_before_parent_close', 'parent_close', 'parent_joined']
        need([e.get('event') for e in event_list] == order, 'Wrong/missing/duplicate event sequence: ' + name)
        need([e.get('seq') for e in event_list] == list(range(1, len(order)+1)), 'Noncontiguous evidence sequence')
        for e in event_list:
            need(e.get('cipher') == CIPHERS[top], 'Wrong cipher')
            need(e.get('scope') == 'encrypted-library-callers' and e.get('product_qualified') is False, 'Incorrect qualification scope')
        by_name = {e['event']: e for e in event_list}
        warm = by_name['warmup_complete']
        for flag in ('command_mux', 'global_padding', 'authenticated_length', 'decoder_reads_serial', 'ciphertext_fully_consumed'):
            need(warm.get(flag) is True, 'Invalid warmup: ' + flag)
        need(warm.get('response_chunks') == 1, 'Response handshake not fully primed')
        blocked = by_name['wire_blocked']
        prefix = 1 if leaf in ('PartialAuthenticatedLength', 'CompletionBeforeClose') else 55
        need(blocked.get('prefix_bytes') == prefix and blocked.get('auth_length_bytes') == 18, 'Wrong ciphertext boundary')
        need(blocked.get('completed_write_bytes_since_capture', -1) >= 0, 'Missing completed physical bytes')
        partial = blocked.get('active_write_consumed_bytes', 0)
        need(0 < partial < blocked.get('active_write_length', 0), 'No actual partial physical Write')
        need(partial + blocked['completed_write_bytes_since_capture'] == prefix, 'Physical prefix accounting mismatch')
        for key in ('parent_writers', 'blocked_pipe_writers', 'active_transport_writes', 'maximum_transport_writes'):
            need(blocked.get(key) == 1, 'Missing/duplicate fixed blocked writer: ' + key)
        stack = blocked.get('blocked_stack', '')
        for fragment in (' [select]:', 'net.(*pipe).write(', '(*encCancelWire).Write(', '(*serverConn).Write(', '(*serverSession).writeLoop('):
            need(fragment in stack, 'Actual blocked-stack frame missing: ' + fragment)
        close = by_name['parent_close']
        need(close.get('real_peer_close') is True and close.get('outer_context_alive') is True, 'Parent was not closed by real peer')
        need(close.get('while_write_blocked') is (leaf == 'ParentTransportError'), 'Wrong parent-error branch')
        joined = by_name['parent_joined']
        for key in ('service_joined', 'writer_joined', 'watcher_joined', 'all_test_workers_joined', 'outer_context_alive'):
            need(joined.get(key) is True, 'Missing final join: ' + key)
        expected_handlers = 3 if leaf == 'ParentTransportError' else 4
        need(joined.get('handler_callbacks_finished') == joined.get('handler_callbacks_expected') == expected_handlers, 'Missing handler joins')
        for key in ('active_transport_writes', 'active_callers', 'retained_streams', 'retained_queue'):
            need(joined.get(key) == 0, 'Retained parent resource: ' + key)
        need(isinstance(joined.get('service_error'), str) and joined['service_error'] not in ('', '<nil>'), 'Real Service error absent')
        need('timeout' not in joined['service_error'].lower() and 'deadline' not in joined['service_error'].lower(), 'Timeout substituted for real parent error')
        failures = joined.get('parent_error_results')
        need(isinstance(failures, list), 'Missing parent caller transport results')
        if leaf == 'ParentTransportError':
            need(len(failures) == 3 and [r.get('caller') for r in failures] == [0, 1, 2], 'Missing/duplicate parent caller identity')
            for failure in failures:
                need(failure.get('bytes') == 0 and failure.get('class') in ('io.ErrClosedPipe', 'net.ErrClosed'), 'Wrong parent transport result')
                message = failure.get('error', '')
                expected = 'io: read/write on closed pipe' if failure['class'] == 'io.ErrClosedPipe' else 'use of closed network connection'
                need(isinstance(message, str) and expected in message and 'timeout' not in message.lower(), 'Missing actual closed transport error')
        else:
            need(failures == [], 'Unexpected parent error callers in normal close')
        continuity = [e for e in event_list if e['event'] == 'cipher_continuity']
        counts = [(1, 3)] if leaf == 'ParentTransportError' else [(1, 3), (18, 11), (22, 13), (24, 13)]
        need(len(continuity) == len(counts), 'Missing nonce epochs')
        for e, (response, request) in zip(continuity, counts):
            need(e.get('response_chunks') == response and e.get('request_chunks') == request, 'Wrong parsed plaintext/chunk counts')
            for key in ('server_data_nonce', 'server_length_nonce', 'client_data_nonce', 'client_length_nonce'):
                need(e.get(key) == response, 'Response nonce discontinuity: ' + key)
            for key in ('upload_data_nonce', 'upload_length_nonce', 'service_data_nonce', 'service_length_nonce'):
                need(e.get(key) == request, 'Request nonce discontinuity: ' + key)
            need(e.get('physical_bytes_exact') is True, 'Unconsumed encrypted bytes')
        if leaf == 'ParentTransportError':
            snapshot = by_name['parent_error_snapshot']
            need(snapshot.get('parent_alive') is True and snapshot.get('no_context_cancel') is True, 'Early parent cleanup')
            need(snapshot.get('pending_callers') == 3 and snapshot.get('queued_callers') == 2 and snapshot.get('blocked_pipe_writers') == 1, 'Parent error did not release blocked and queued callers')
            need(joined.get('real_write_errors', 0) >= 1, 'No real transport Write error')
            need(joined.get('parent_error_callers_closed') == 3, 'Blocked/queued caller errors were not verified')
            continue
        need(joined.get('real_write_errors') == 0, 'Recovery ended with transport Write failure')
        restored = by_name['restore_reads']
        need(restored.get('prefix_bytes') == prefix and restored.get('unchanged_prefix_replay') is True and restored.get('parent_alive') is True, 'Ciphertext prefix restoration invalid')
        if leaf == 'CompletionBeforeClose':
            complete = by_name['completion_before_close']
            need(complete.get('caller_success') is True and complete.get('operation_done') is True and complete.get('parent_alive') is True and complete.get('caller_bytes') == 65535, 'No real completion-before-Close')
        else:
            snapshot = by_name['cancel_snapshot']
            queued = leaf == 'QueuedCancel'
            need(snapshot.get('queued') is queued and snapshot.get('operation_done') is queued, 'Wrong queued/in-flight cancellation branch')
            for key in ('caller_closed', 'caller_joined', 'operation_canceled', 'parent_alive'):
                need(snapshot.get(key) is True, 'Missing pre-restore cancellation: ' + key)
            need(snapshot.get('parent_deadline_changes') == snapshot.get('parent_close_calls') == 0, 'Association Close modified parent transport')
            need(snapshot.get('caller_bytes') == 0 and snapshot.get('active_callers') == int(queued), 'Canceled caller retained or reported bytes')
            bound = snapshot.get('cancel_bound_ns')
            need(bound == 3_000_000_000 and 0 <= snapshot.get('cancel_elapsed_ns', -1) < bound, 'Cancellation not bounded')
            for key in ('parent_writers', 'blocked_pipe_writers', 'active_transport_writes'):
                need(snapshot.get(key) == 1, 'Writer not retained before reads restored')
            need(snapshot.get('streams') == 3 and snapshot.get('owned_frames') == 2 and snapshot.get('owned_bytes') == 65557, 'Unexpected bounded ownership snapshot')
            need(snapshot.get('handler_callbacks_finished') == 3 and snapshot.get('handler_callbacks_active') == 0, 'Callbacks retained before reads restored')
        siblings = by_name['siblings_recovered']
        for key in ('same_parent', 'tuple_payload_exact', 'parent_alive'):
            need(siblings.get(key) is True, 'Sibling recovery absent: ' + key)
        for key, size in (('udp_upload', 60000), ('udp_reply', 60000), ('tcp_upload', 32768), ('tcp_reply', 70007)):
            need(siblings.get(key) == size, 'Sibling payload/chunk boundary not covered: ' + key)
        fresh = by_name['fresh_session_recovered']
        for key in ('actual_encrypted_new', 'same_parent', 'tuple_payload_exact', 'parent_alive'):
            need(fresh.get(key) is True, 'Fresh encrypted session admission/recovery absent: ' + key)
        need(fresh.get('session_id') == 4 and fresh.get('udp_upload') == 4097 and fresh.get('udp_reply') == 32768, 'Fresh encrypted session payload/boundary missing')
        need(fresh.get('end_count') == 1 and fresh.get('handler_callbacks_finished') == 4, 'Fresh stream End/callback not joined')
        drained = by_name['drained_before_parent_close']
        need(drained.get('parent_alive') is True and drained.get('each_end_once') is True and drained.get('end_count') == 4, 'Incomplete/duplicate End evidence')
        for key in ('active_transport_writes', 'active_callers', 'handler_callbacks_active'):
            need(drained.get(key) == 0, 'Work retained before real parent close: ' + key)
    return {'top_level_cases': len(CIPHERS), 'leaf_cases': len(events), 'scope': 'encrypted-library-callers', 'product_qualified': False}
